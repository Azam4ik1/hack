words=[]
for si,(s,e,t) in enumerate(segs):
    toks=[]
    for w in t.split():
        if w=='—': toks[-1]+=' —'; continue
        toks.append(w.replace('_',' '))
    def wt(w):
        if re.search(r'\d',w): return 22 if '1972' in w else 8
        return len(re.sub(r'\W','',w))+1.5
    ws=[wt(w) for w in toks]; tot=sum(ws); c=s
    for w,k in zip(toks,ws):
        d=(e-s)*k/tot; words.append({"text":w,"start":round(c,3),"end":round(c+d,3),"seg":si}); c+=d
clauses=[];cur=[]
for w in words:
    if cur and w['seg']!=cur[-1]['seg']: clauses.append(cur);cur=[]
    cur.append(w)
    if re.search(r'[.?!:,»…]$',w['text']): clauses.append(cur);cur=[]
if cur: clauses.append(cur)
SHORT={'и','не','в','на','за','от','без','а','но','что','так','ни','его','он','я','с','к','по','им','их','мне','вам','ему'}
L=lambda ws:len(' '.join(w['text'] for w in ws))
out=[]
for cl in clauses:
    n=max(1,math.ceil(L(cl)/22))
    if n==1: out.append(cl);continue
    target=L(cl)/n;parts=[];p=[]
    for w in cl:
        if p and L(p+[w])>target+4 and len(parts)<n-1: parts.append(p);p=[]
        p.append(w)
    parts.append(p)
    for i in range(len(parts)-1):
        while len(parts[i])>1 and re.sub(r'\W','',parts[i][-1]['text']).lower() in SHORT:
            parts[i+1].insert(0,parts[i].pop())
    if len(parts)>1 and len(parts[-1])==1 and L(parts[-2]+parts[-1])<=26:
        last=parts.pop(); parts[-1]+=last
    out+=[p for p in parts if p]
for p in out:
    for w in p: w.pop('seg',None)
res=[{"start":p[0]['start'],"end":p[-1]['end'],"words":p} for p in out]
json.dump(res,open('src/captions17.json','w'),ensure_ascii=False,indent=1)
